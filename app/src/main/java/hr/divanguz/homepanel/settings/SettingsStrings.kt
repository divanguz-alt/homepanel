/** Croatian when chosen; English (the source text) otherwise. */
internal fun tr(en: String): String =
    if (SettingsLanguage.croatian.value) SettingsLanguage.HR[en] ?: en else en

/** [tr] for text with values: "%s events in the next %s days". */
internal fun trf(en: String, vararg args: Any?): String = tr(en).format(*args)
